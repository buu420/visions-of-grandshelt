std::string_view localized_map_title(int map, std::string_view locale) {
    if (locale == "en") return area_input_detail::map_title(map);
    const auto* language = std::find(std::begin(languages), std::end(languages), locale);
    if (language == std::end(languages)) return {};
    const auto* place = std::lower_bound(std::begin(places), std::end(places), map,
        [](const PlaceIndex& entry, int id) { return entry.map < id; });
    if (place == std::end(places) || place->map != map) return {};
    return names[place->name][static_cast<std::size_t>(language - std::begin(languages))];
}
