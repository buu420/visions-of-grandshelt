"""Render the walking destination catalog from the exact-build transition catalog."""
import argparse
from collections import defaultdict
import json
from pathlib import Path

BUILD = 24250053


def condition_info(row):
    if row is None:
        return "", True
    return row["raw"] or "", row["supported"] or row["trivially_true"]


def walking(movement):
    return movement["changes"] is not True or movement["type"] == "Walking"


def walk_connected(map_id, entry, gate, mesh):
    landing = entry["nav"].get(mesh, {})
    approach = gate["source_nav"].get(mesh, {})
    if set(landing.get("components", ())) & set(approach.get("components", ())):
        return True
    # Mitra's detached interiors use the native collision-checked room routes.
    room = entry["area_ids"]
    return (map_id == 2000 and not landing.get("approachable") and len(room) == 1
            and 2 <= room[0] <= 9 and room[0] in gate["source_areas"]["authored"])


def wide(text):
    return "L" + json.dumps(text or "", ensure_ascii=False)


def render(source):
    catalog = json.loads(source.read_text(encoding="utf-8"))
    assert catalog["schema"] == "ffrs-transition-catalog/1"
    assert catalog["build"]["steam_build"] == BUILD
    maps = {row["map_id"]: row for row in catalog["maps"]
            if row["playable"] and row["level"] and row["name_en"]}
    levels = {map_id: row["level"] for map_id, row in maps.items()}
    entries = {}
    for map_id, row in maps.items():
        by_point = defaultdict(list)
        for entry in row["entries"]:
            if entry["point_id"] is not None and entry["point_id"] >= -1:
                by_point[entry["point_id"]].append(entry)
        entries[map_id] = by_point

    rows, gates, departures = [], [], []
    for gate in catalog["exits"]:
        map_id, trigger = gate["source_map"], gate["unique_id"]
        if (map_id not in maps or trigger is None or trigger < 0 or gate["uid_siblings"]
                or gate["resolution"]["rule"] == "unknown_mode"
                or gate["native_class"] != "/Script/mucha.CPP_MapTransitionTrigger"):
            continue
        available, known = condition_info(gate["trigger_condition"])
        if not known:
            continue
        streaming = {
            rule["condition"] for rule in gate["sublevel_load"]
            if rule.get("source") == "mainProgressLoadLevelList" and rule.get("condition")
        }
        if len(streaming) > 1:
            continue
        variants = []
        for row in gate["variants"]:
            destination, entry = row["map_id"], row["point_id"]
            condition, known = condition_info(row["condition"])
            index = row.get("row_index")
            movement = gate["movement"] if index is None else gate["rows"][index]["movement"]
            ordinary = (not row["blocker"] and destination in levels
                        and entry is not None and entry >= -1 and walking(movement))
            variants.append((destination if destination is not None else -1,
                             entry if entry is not None else -2, condition, ordinary, known))
        if not any(row[3] for row in variants):
            continue
        mesh = maps[map_id]["walk_navdata"]
        reachable = [
            point for point, anchors in sorted(entries[map_id].items())
            if len(anchors) == 1 and walk_connected(map_id, anchors[0], gate, mesh)
        ]
        if not reachable:
            continue
        gates.append((map_id, trigger, available, next(iter(streaming), ""),
                      len(rows), len(variants), len(departures), len(reachable)))
        rows.extend(variants)
        departures.extend(reachable)

    output = [
        "// Generated by tools/generate-travel-catalog.py from Steam build 24250053.",
        "// Walking connectivity is checked again by the game for each loaded leg.",
        "inline constexpr MapLevel map_levels[]{",
    ]
    for map_id, level in sorted(levels.items()):
        output.append(f"    {{{map_id},{wide(level)}}},")
    output.append("};")
    output.append("inline constexpr Variant variants[]{")
    for map_id, point, condition, ordinary, known in rows:
        output.append(f"    {{{{{map_id},{point}}},{wide(condition)},{str(ordinary).lower()},{str(known).lower()}}},")
    output.append("};")
    output.append("inline constexpr Gate gates[]{")
    for map_id, trigger, condition, streaming, first_row, row_count, first_point, point_count in gates:
        output.append(f"    {{{map_id},{trigger},{wide(condition)},{wide(streaming)},"
                      f"{first_row},{row_count},{first_point},{point_count}}},")
    output.append("};")
    output.append("inline constexpr int departure_entries[]{")
    for offset in range(0, len(departures), 20):
        output.append("    " + ",".join(str(point) for point in departures[offset:offset + 20]) + ",")
    output.append("};")
    print(f"{len(levels)} maps, {len(gates)} linked gates, {len(rows)} ordered variants, {len(departures)} entry links")
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(render(args.catalog), encoding="utf-8")

